# Forcefield option map: short name → (forcefield xml list, addSolvent water model string).
# addSolvent does not accept 'opc' as a model string, so ff19 uses 'tip4pew' as a geometry
# placeholder — OPC parameters are then applied via amber14/opc.xml. desamber is TIP4P-D,
# which shares the 4-site tip4pew geometry (the M-site is then placed by its own virtual site).
FORCEFIELD_OPTIONS: dict[str, tuple[list[str], str]] = {
    'ff14': (FORCEFIELDS, 'tip3p'),
    'ff19': (['amber19/protein.ff19SB.xml', 'amber19/opc.xml'], 'tip4pew'),
    'desamber': (DESAMBER_FORCEFIELDS, 'tip4pew'),
}

# Force fields that carry their own probe template in the ffxml (DES-Amber ships a GAFF
# benzene PRB template). The probe must NOT be registered as an OpenFF molecule with the
# SystemGenerator - the bundled template parametrises every PRB copy (matched by graph),
# keeping exact parity with the GROMACS reference the XML was validated against.
TEMPLATE_PROBE_FORCEFIELDS = frozenset({'desamber'})


def uses_template_probe(
        forcefield: str,
        probe_type: str = 'benzene',
        probe_ff_path: str | None = None,
) -> bool:
    """Return whether the built-in benzene template should parameterize the probe."""
    return (
        forcefield in TEMPLATE_PROBE_FORCEFIELDS
        and probe_type == 'benzene'
        and probe_ff_path is None
    )

